"""
stage4_conditional.py — STAGE 4: does alignment retain targeting information
once exposure is controlled INDEPENDENTLY?

Three conditions compared on identical data:

  (1) no exposure control      pool all exposures, compare targeted vs
                               untargeted directly
  (2) oracle true-T control    stratify on the simulator's true T
  (3) estimated-T control      stratify on T-hat from onset_estimator, which
                               never sees alignment or the targeting label

Alignment in (2) and (3) is computed by TEMPORAL CROSS-FITTING: onset is fitted
on odd-indexed samples of the pre-window, alignment on even-indexed samples, so
the onset estimate and the final test do not share observations.

Cases the estimator declines ("onset not identifiable") are reported
separately rather than silently dropped, because dropping them would let the
estimator select the cases it happens to do well on.

PREREGISTERED READING — fixed before running
--------------------------------------------
  SURVIVES        estimated-T AUC within 0.05 of oracle-T AUC, in the
                  detectable regime, across structures
  THEORETICALLY   oracle-T AUC high but estimated-T AUC degrades by more than
  IDENTIFIABLE    0.10, or the estimator declines in most cases
  ONLY
  DIES            oracle-T AUC itself collapses (already excluded by Stage 1)

A flattering aggregate is not accepted: results are reported per stratum and
per structure, and the worst regime is reported alongside the median.

Run:  python3 analysis/experiments/stage4_conditional.py
"""

from __future__ import annotations

import os
import sys

import numpy as np

_HERE = os.path.dirname(__file__)
sys.path.insert(0, _HERE)
sys.path.insert(0, os.path.join(_HERE, ".."))

from exposure_stage1_oracle import (Config, simulate, calibrate,      # noqa: E402
                                    d_isotropic, d_stiff_sub, auc)
from onset_estimator import estimate_onset, alignment_crossfit        # noqa: E402

SEEDS = range(30)
EXPOS = [3.0, 10.0, 30.0, 60.0, 120.0]
SEVS = [10.0, 30.0]            # 0.5 and 1.5 baseline SD (detectable regime)
STRUCTS = [Config("wide-rotated"),
           Config("wide-diagonal", rotate=False),
           Config("high-noise", sigma=2.0),
           Config("narrow-rotated", k_lo=0.60, k_hi=2.40)]


def collect(cfg, dirfn, T, sev):
    s = calibrate(cfg, dirfn, T, sev)
    rows = []
    for i in SEEDS:
        X = simulate(cfg, dirfn(cfg, i), s, T, i)
        est = estimate_onset(X, cfg)                     # odd samples
        rows.append({"A": alignment_crossfit(X, cfg),    # even samples
                     "T_true": T,
                     "T_hat": est["T_hat"],
                     "ident": est["identifiable"]})
    return rows


def main() -> str:
    data = {}
    for cfg in STRUCTS:
        for sev in SEVS:
            for T in EXPOS:
                data[(cfg.name, sev, T, "stiff")] = collect(cfg, d_stiff_sub, T, sev)
                data[(cfg.name, sev, T, "iso")] = collect(cfg, d_isotropic, T, sev)

    out, w = [], lambda s: out.append(s)
    w("# Stage 4 — conditional test with estimated exposure\n")
    w("Generated by `analysis/experiments/stage4_conditional.py`. Alignment is "
      "cross-fitted: onset is estimated on odd-indexed samples, alignment "
      "computed on even-indexed samples.\n")

    # --- (1) no control: pool all exposures within a structure/severity ---
    w("\n## 1. No exposure control\n")
    w("\n| structure | severity | AUC (pooled over exposures) |")
    w("|---|:--:|:--:|")
    nc = []
    for cfg in STRUCTS:
        for sev in SEVS:
            st = [r["A"] for T in EXPOS for r in data[(cfg.name, sev, T, "stiff")]]
            it = [r["A"] for T in EXPOS for r in data[(cfg.name, sev, T, "iso")]]
            v = auc(st, it)
            nc.append(v)
            w(f"| {cfg.name} | {sev:g} | {v:.3f} |")
    w(f"\nmedian **{np.median(nc):.3f}**\n")

    # --- (2) oracle control ---
    w("\n## 2. Oracle true-T control\n")
    orc = {}
    for cfg in STRUCTS:
        for sev in SEVS:
            v = [auc([r["A"] for r in data[(cfg.name, sev, T, "stiff")]],
                     [r["A"] for r in data[(cfg.name, sev, T, "iso")]])
                 for T in EXPOS]
            orc[(cfg.name, sev)] = v
    allo = [x for v in orc.values() for x in v]
    w(f"\nper-stratum median **{np.median(allo):.3f}**, "
      f"min {np.min(allo):.3f}, fraction > 0.65 {np.mean(np.array(allo)>0.65):.0%}\n")

    # --- (3) estimated-T control ---
    w("\n## 3. Estimated-T control\n")
    w("\nCases are binned by T-hat rather than true T. Bins follow the "
      "exposure grid; a case is assigned to the nearest grid value.\n")
    grid = np.array(EXPOS)
    est = {}
    declined = {}
    for cfg in STRUCTS:
        for sev in SEVS:
            st_all = [r for T in EXPOS for r in data[(cfg.name, sev, T, "stiff")]]
            it_all = [r for T in EXPOS for r in data[(cfg.name, sev, T, "iso")]]
            declined[(cfg.name, sev)] = (
                np.mean([not r["ident"] for r in st_all + it_all]))
            vals = []
            for g in grid:
                sb = [r["A"] for r in st_all if r["ident"] and
                      grid[np.argmin(np.abs(grid - r["T_hat"]))] == g]
                ib = [r["A"] for r in it_all if r["ident"] and
                      grid[np.argmin(np.abs(grid - r["T_hat"]))] == g]
                if len(sb) >= 5 and len(ib) >= 5:
                    vals.append(auc(sb, ib))
            est[(cfg.name, sev)] = vals
    alle = [x for v in est.values() for x in v]
    w(f"\nper-bin median **{np.median(alle):.3f}**, min {np.min(alle):.3f}, "
      f"fraction > 0.65 {np.mean(np.array(alle)>0.65):.0%} "
      f"({len(alle)} usable bins)\n")

    # --- head to head ---
    w("\n## 4. Head to head\n")
    w("\n| structure | severity | no control | oracle T | estimated T | declined |")
    w("|---|:--:|:--:|:--:|:--:|:--:|")
    rows = []
    for cfg in STRUCTS:
        for sev in SEVS:
            o = np.median(orc[(cfg.name, sev)])
            e = np.median(est[(cfg.name, sev)]) if est[(cfg.name, sev)] else float("nan")
            n = auc([r["A"] for T in EXPOS for r in data[(cfg.name, sev, T, "stiff")]],
                    [r["A"] for T in EXPOS for r in data[(cfg.name, sev, T, "iso")]])
            rows.append((n, o, e))
            w(f"| {cfg.name} | {sev:g} | {n:.3f} | {o:.3f} | {e:.3f} "
              f"| {declined[(cfg.name, sev)]:.0%} |")
    n_, o_, e_ = (np.median([r[i] for r in rows]) for i in range(3))
    gap = o_ - e_
    w(f"\nmedian: no control {n_:.3f} · oracle {o_:.3f} · estimated {e_:.3f}")
    w(f"\n**oracle minus estimated = {gap:+.3f}**\n")

    verdict = ("SURVIVES" if gap <= 0.05 else
               "THEORETICALLY IDENTIFIABLE ONLY" if gap > 0.10 else
               "SURVIVES WITH DEGRADATION")
    w("\n## 5. Verdict against the preregistered reading\n")
    w("\n| criterion | value | threshold |")
    w("|---|:--:|:--:|")
    w(f"| oracle − estimated | {gap:+.3f} | survives ≤ 0.05 / theory-only > 0.10 |")
    w(f"| worst-case estimated-T bin | {np.min(alle):.3f} | – |")
    w(f"| median declined rate | "
      f"{np.median(list(declined.values())):.0%} | – |")
    w(f"\n### Verdict: **{verdict}**\n")
    return "\n".join(out)


if __name__ == "__main__":
    txt = main()
    with open(os.path.join(_HERE, "..", "results",
                           "stage4_conditional.md"), "w") as fh:
        fh.write(txt)
    print(txt)
