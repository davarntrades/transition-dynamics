"""
alignment_identifiability.py — Follow-up to the homeostatic premise test.

The main experiment matched conditions on displacement MAGNITUDE ||delta||.
That is the wrong metric for asking whether the alignment statistic adds
anything clinically, because conventional monitoring does not see ||delta|| —
it sees each channel against its own normal range.

Two questions the main experiment could not answer:

  Q1  Given two patients who look IDENTICAL to conventional monitoring,
      does alignment still distinguish a targeted insult from an untargeted
      one, and does covariance drift?

  Q2  In the regime where alignment is informative, is its response to
      TARGETING larger than its response to EXPOSURE DURATION? If not, an
      observed alignment cannot be attributed to targeting in data where
      time-since-onset is unknown, which is the normal clinical situation.

Conditions are matched on max univariate z, i.e. on what a clinician sees.
Univariate AUC near 0.50 is therefore true BY CONSTRUCTION and is not a
finding; covariance drift is not matched on, so its AUC is a finding.

Run:  python3 analysis/experiments/alignment_identifiability.py
"""

from __future__ import annotations

import os
import sys

import numpy as np

_HERE = os.path.dirname(__file__)
sys.path.insert(0, _HERE)
sys.path.insert(0, os.path.join(_HERE, ".."))

import homeostatic_premise as H          # noqa: E402

SEEDS = range(30)
EXPO = 60.0


def auc(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    return float(((a[:, None] > b[None, :]).sum()
                  + 0.5 * (a[:, None] == b[None, :]).sum()) / (len(a) * len(b)))


def stiff_subspace(i, m=3):
    """Targeting distributed over the m stiffest coordinates, not just one.
    Single-coordinate targeting is maximally favourable to a univariate
    detector, so the distributed case is the fair one."""
    r = np.random.default_rng(7000 + i).normal(0, 1, m)
    v = np.zeros(H.P)
    v[-m:] = r / np.linalg.norm(r)
    return v


def run(fn, scale, T=EXPO):
    return [H.measure(H.simulate(fn(i), scale, T, i)) for i in SEEDS]


def match_uni(fn, T, target_uni, tag):
    """Scale the force so mean max-univariate-z equals target."""
    s = H.calibrate(fn, T, 1.0, tag=tag)
    for _ in range(4):
        u = float(np.mean([x["uni"] for x in run(fn, s, T)]))
        if u < 1e-9:
            break
        s *= target_uni / u
    return s


def main() -> str:
    out = []
    w = out.append
    w("# Alignment Identifiability — follow-up\n")
    w("Generated by `analysis/experiments/alignment_identifiability.py`.\n")
    w("\nConditions matched on **max univariate z** — what conventional "
      "monitoring sees. Univariate AUC ≈ 0.50 is true by construction. "
      "Covariance drift is not matched on, so its AUC is a finding.\n")
    w("\n`maxUni = |δ|/(σ₀/√n)`, so maxUni = 10 is a displacement of "
      "**0.50 baseline SD** of that channel; maxUni = 4 is 0.20 SD.\n")

    w("\n## Q1. Does alignment add anything beyond conventional monitoring?\n")
    w("\n| displacement | condition | A | dG | AUC uni | **AUC A** | AUC dG |")
    w("|:--:|---|:--:|:--:|:--:|:--:|:--:|")
    for tgt in (4.0, 10.0, 57.0):
        s_iso = match_uni(H.isotropic_dir, EXPO, tgt, f"i{tgt}")
        iso = run(H.isotropic_dir, s_iso)
        sd = tgt / 20.0
        w(f"| {sd:.2f} SD | isotropic (reference) | "
          f"{np.mean([x['A'] for x in iso]):.3f} | "
          f"{np.mean([x['dG'] for x in iso]):.2f} | – | – | – |")
        for nm, fn in (("stiff-subspace", stiff_subspace),
                       ("single-stiff", lambda i: H.STIFF)):
            s = match_uni(fn, EXPO, tgt, f"{nm}{tgt}")
            r = run(fn, s)
            w(f"| | {nm} | {np.mean([x['A'] for x in r]):.3f} | "
              f"{np.mean([x['dG'] for x in r]):.2f} | "
              f"{auc([x['uni'] for x in r], [x['uni'] for x in iso]):.2f} | "
              f"**{auc([x['A'] for x in r], [x['A'] for x in iso]):.2f}** | "
              f"{auc([x['dG'] for x in r], [x['dG'] for x in iso]):.2f} |")

    w("\n## Q2. Targeting versus exposure, in the operating regime\n")
    TGT = 10.0
    w(f"\nMatched at maxUni = {TGT:g} (0.50 baseline SD), where alignment is "
      "informative.\n")
    w("\n| condition | A | AUC vs isotropic T=60 | targeting present? |")
    w("|---|:--:|:--:|:--:|")
    s = match_uni(H.isotropic_dir, EXPO, TGT, "q2ref")
    ref = run(H.isotropic_dir, s)
    w(f"| isotropic, T=60 | {np.mean([x['A'] for x in ref]):.3f} | – | no |")
    expo_aucs = []
    for T in (1.0, 12.0, 120.0):
        s = match_uni(H.isotropic_dir, T, TGT, f"q2e{T}")
        r = run(H.isotropic_dir, s, T)
        a = auc([x["A"] for x in r], [x["A"] for x in ref])
        expo_aucs.append(a)
        w(f"| isotropic, T={T:g} | {np.mean([x['A'] for x in r]):.3f} | "
          f"{a:.2f} | **no** |")
    s = match_uni(stiff_subspace, EXPO, TGT, "q2t")
    r = run(stiff_subspace, s)
    targ_auc = auc([x["A"] for x in r], [x["A"] for x in ref])
    w(f"| stiff-subspace, T=60 | {np.mean([x['A'] for x in r]):.3f} | "
      f"{targ_auc:.2f} | **yes** |")

    w(f"\n**Exposure alone reaches AUC {max(expo_aucs):.2f}; targeting reaches "
      f"{targ_auc:.2f}.** The two are comparable, so in the operating regime "
      "an observed alignment cannot be attributed to targeting unless "
      "time-since-onset is known.\n")
    return "\n".join(out)


if __name__ == "__main__":
    txt = main()
    with open(os.path.join(_HERE, "..", "results",
                           "alignment_identifiability.md"), "w") as fh:
        fh.write(txt)
    print(txt)
